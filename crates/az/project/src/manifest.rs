/// Read, parse, and validate `azoth.toml` at `root`.
///
/// # Errors
///
/// Returns [`ProjectManifestError::Read`] if the file cannot be read,
/// [`ProjectManifestError::Parse`] if it is not valid TOML, or any error
/// [`ProjectManifest::validate`] returns.
pub fn load_project_manifest(
    root: impl AsRef<Path>,
) -> Result<ProjectManifest, ProjectManifestError> {
    let path = project_manifest_path(root);
    let manifest_str =
        std::fs::read_to_string(&path).map_err(|source| ProjectManifestError::Read {
            path: path.clone(),
            source,
        })?;
    let manifest: ProjectManifest =
        toml::from_str(&manifest_str).map_err(|source| ProjectManifestError::Parse {
            path: path.clone(),
            source: Box::new(source),
        })?;
    manifest.validate()?;
    Ok(manifest)
}

/// Validate `manifest` and write it to `azoth.toml` under `root`.
///
/// Validation runs first, so a rejected manifest never reaches disk.
///
/// # Errors
///
/// Returns any error [`ProjectManifest::validate`] returns,
/// [`ProjectManifestError::Serialize`] if the manifest cannot be rendered as
/// TOML, or [`ProjectManifestError::Write`] if `root` cannot be created or the
/// file cannot be written.
pub fn write_project_manifest(
    root: impl AsRef<Path>,
    manifest: &ProjectManifest,
) -> Result<(), ProjectManifestError> {
    manifest.validate()?;

    let root = root.as_ref();
    std::fs::create_dir_all(root).map_err(|source| ProjectManifestError::Write {
        path: root.to_path_buf(),
        source,
    })?;

    let path = project_manifest_path(root);
    let manifest_str = toml::to_string_pretty(manifest)?;
    std::fs::write(&path, manifest_str)
        .map_err(|source| ProjectManifestError::Write { path, source })
}

