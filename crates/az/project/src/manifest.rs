/// Manifest-published schema for the project-owned `[gem_config."<id>"]` table.
///
/// The deliberately small type vocabulary is lossless for TOML and keeps
/// configuration validation available before any gem code is loaded.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq, Default)]
#[serde(deny_unknown_fields)]
pub struct GemConfigurationSchema {
    #[serde(default)]
    pub allow_unknown_fields: bool,

    #[serde(default, skip_serializing_if = "BTreeMap::is_empty")]
    pub fields: BTreeMap<String, GemConfigurationField>,
}

impl GemConfigurationSchema {
    fn validate(&self, gem_id: &str) -> Result<(), ProjectManifestError> {
        for field in self.fields.keys() {
            validate_portable_package_id("gem configuration field", field).map_err(|error| {
                ProjectManifestError::InvalidGemConfigurationSchema {
                    gem_id: gem_id.to_string(),
                    reason: error.to_string(),
                }
            })?;
        }
        Ok(())
    }

    fn validate_config(
        &self,
        gem_id: &str,
        config: &BTreeMap<String, serde_json::Value>,
    ) -> Result<(), ProjectManifestError> {
        for (field, declaration) in &self.fields {
            match config.get(field) {
                Some(value) if declaration.kind.matches(value) => {}
                Some(value) => {
                    return Err(ProjectManifestError::InvalidGemConfiguration {
                        gem_id: gem_id.to_string(),
                        reason: format!(
                            "field `{field}` must be {}, found {}",
                            declaration.kind,
                            json_value_kind(value)
                        ),
                    });
                }
                None if declaration.required => {
                    return Err(ProjectManifestError::InvalidGemConfiguration {
                        gem_id: gem_id.to_string(),
                        reason: format!("required field `{field}` is missing"),
                    });
                }
                None => {}
            }
        }
        if !self.allow_unknown_fields
            && let Some(field) = config
                .keys()
                .find(|field| !self.fields.contains_key(*field))
        {
            return Err(ProjectManifestError::InvalidGemConfiguration {
                gem_id: gem_id.to_string(),
                reason: format!("unknown field `{field}`"),
            });
        }
        Ok(())
    }
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
#[serde(deny_unknown_fields)]
pub struct GemConfigurationField {
    #[serde(rename = "type")]
    pub kind: GemConfigurationValueKind,

    #[serde(default)]
    pub required: bool,
}

#[derive(Debug, Clone, Copy, Serialize, Deserialize, PartialEq, Eq)]
#[serde(rename_all = "kebab-case")]
pub enum GemConfigurationValueKind {
    String,
    Integer,
    Number,
    Boolean,
    Array,
    Table,
}

impl GemConfigurationValueKind {
    fn matches(self, value: &serde_json::Value) -> bool {
        match self {
            Self::String => value.is_string(),
            Self::Integer => value.as_i64().is_some() || value.as_u64().is_some(),
            Self::Number => value.is_number(),
            Self::Boolean => value.is_boolean(),
            Self::Array => value.is_array(),
            Self::Table => value.is_object(),
        }
    }
}

impl std::fmt::Display for GemConfigurationValueKind {
    fn fmt(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        formatter.write_str(match self {
            Self::String => "a string",
            Self::Integer => "an integer",
            Self::Number => "a number",
            Self::Boolean => "a boolean",
            Self::Array => "an array",
            Self::Table => "a table",
        })
    }
}

fn json_value_kind(value: &serde_json::Value) -> &'static str {
    match value {
        serde_json::Value::Null => "null",
        serde_json::Value::Bool(_) => "a boolean",
        serde_json::Value::Number(number) if number.is_i64() || number.is_u64() => "an integer",
        serde_json::Value::Number(_) => "a number",
        serde_json::Value::String(_) => "a string",
        serde_json::Value::Array(_) => "an array",
        serde_json::Value::Object(_) => "a table",
    }
}

