fn canonical_engine_root(root: impl AsRef<Path>) -> Result<PathBuf, ProjectManifestError> {
    let root = root.as_ref();
    if root.as_os_str().is_empty() {
        return Err(ProjectManifestError::InvalidEngineRoot {
            path: root.to_path_buf(),
            reason: "path cannot be empty".to_string(),
        });
    }

    let root = root
        .canonicalize()
        .map_err(|source| ProjectManifestError::Read {
            path: root.to_path_buf(),
            source,
        })?;
    Ok(root)
}

fn resolve_engine_gems_from_manifest(
    engine_root: &Path,
    manifest: &EngineManifest,
) -> Result<Vec<ResolvedEngineGem>, ProjectManifestError> {
    manifest.validate()?;
    let mut gems = Vec::with_capacity(manifest.gems.len());
    for declaration in &manifest.gems {
        gems.push(resolve_engine_gem_declaration(engine_root, declaration)?);
    }
    Ok(gems)
}

fn resolve_engine_gem_declaration(
    engine_root: &Path,
    declaration: &EngineGem,
) -> Result<ResolvedEngineGem, ProjectManifestError> {
    declaration.validate()?;
    let root = project_relative_path(engine_root, &declaration.path);
    let manifest = load_gem_manifest(&root)?;
    if manifest.gem.id != declaration.id {
        return Err(ProjectManifestError::EngineGemIdMismatch {
            declared: declaration.id.clone(),
            actual: manifest.gem.id,
            path: gem_manifest_path(&root),
        });
    }

    Ok(ResolvedEngineGem {
        declaration: declaration.clone(),
        root,
        manifest,
    })
}

