/// Resolves the engine selected for an existing project-local workspace.
///
/// Relocatable host tools may live in a project's `target` directory rather
/// than beneath the engine checkout. In that layout the generated Cargo config
/// is the durable local record of the selected engine root. An explicit
/// `AZOTH_ENGINE_ROOT` remains authoritative, while an executable installed
/// beneath an engine checkout remains self-describing.
///
/// # Errors
///
/// Returns [`ProjectManifestError::Read`] if the project-local generated Cargo
/// config exists but cannot be read, plus any error [`resolve_engine_root_at`]
/// returns for whichever root wins.
pub fn resolve_project_engine_root(
    project_root: impl AsRef<Path>,
) -> Result<PathBuf, ProjectManifestError> {
    if std::env::var_os(AZOTH_ENGINE_ROOT_ENV).is_some() {
        return resolve_engine_root();
    }
    if let Some(root) = engine_root_from_current_executable() {
        return resolve_engine_root_at(root);
    }

    if let Some(root) = project_engine_root_from_generated_config(project_root)? {
        return resolve_engine_root_at(root);
    }

    resolve_engine_root()
}

fn project_engine_root_from_generated_config(
    project_root: impl AsRef<Path>,
) -> Result<Option<PathBuf>, ProjectManifestError> {
    let config_path = project_local_cargo_config_path(project_root);
    match std::fs::read_to_string(&config_path) {
        Ok(config) => {
            if let Some(fingerprint) =
                crate::patch_table::parse_project_engine_patch_fingerprint(&config)
            {
                return Ok(Some(PathBuf::from(fingerprint.selected_engine_root)));
            }
        }
        Err(source) if source.kind() == std::io::ErrorKind::NotFound => {}
        Err(source) => {
            return Err(ProjectManifestError::Read {
                path: config_path,
                source,
            });
        }
    }
    Ok(None)
}

/// Canonicalize `root` and confirm it holds a valid engine manifest.
