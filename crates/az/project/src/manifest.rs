/// Resolve the project's gem closure: declared gems, their transitive gem
/// dependencies, and the union of capabilities those selections imply.
///
/// # Errors
///
/// Returns any error [`ProjectManifest::validate`] returns, plus
/// [`ProjectManifestError::ProjectGemIdMismatch`] if a path gem's manifest
/// declares another id, [`ProjectManifestError::AmbiguousGemProvenance`] if a
/// gem is homed in both the project and the engine,
/// [`ProjectManifestError::UnknownGemDependency`] or
/// [`ProjectManifestError::GemDependencyVersionMismatch`] if the closure cannot
/// be satisfied, [`ProjectManifestError::GemDependencyCycle`] if it is
/// circular, [`ProjectManifestError::UnknownGemCapability`] if a selection
/// names a capability no manifest declares, and
/// [`ProjectManifestError::UnknownConfiguredGem`],
/// [`ProjectManifestError::InvalidConfiguredGemHome`], or
/// [`ProjectManifestError::InvalidGemConfiguration`] if `[gem_config]` does not
/// match the resolved set. Engine resolution errors surface when the selection
/// requires an engine.
pub fn resolve_project_gems(
    project_root: impl AsRef<Path>,
    manifest: &ProjectManifest,
) -> Result<Vec<ResolvedProjectGem>, ProjectManifestError> {
    manifest.validate()?;
    let project_root = project_root.as_ref();
    let project_candidates = load_project_gem_candidates(project_root, manifest)?;
    let engine_root = if project_selection_requires_engine(manifest, &project_candidates) {
        resolve_project_engine_at(resolve_project_engine_root(project_root)?, manifest)?.root
    } else {
        default_engine_root()
    };
    resolve_project_gems_with_candidates(project_root, &engine_root, manifest, project_candidates)
}

/// Resolve the engine this project builds against, from the ambient selection.
///
/// # Errors
///
/// Returns any error [`resolve_engine_root`], [`ProjectManifest::validate`],
/// and [`resolve_engine_graph_at`] return, plus
/// [`ProjectManifestError::EngineVersionMismatch`] if the resolved engine does
/// not satisfy the project's `engine_version`.
pub fn resolve_project_engine(
    manifest: &ProjectManifest,
) -> Result<ResolvedProjectEngine, ProjectManifestError> {
    resolve_project_engine_at(resolve_engine_root()?, manifest)
}

fn resolve_project_engine_at(
    engine_root: impl AsRef<Path>,
    manifest: &ProjectManifest,
) -> Result<ResolvedProjectEngine, ProjectManifestError> {
    manifest.validate()?;
    let engine_graph = resolve_engine_graph_at(engine_root)?;
    validate_project_engine(&engine_graph.manifest, manifest)?;
    Ok(ResolvedProjectEngine {
        root: engine_graph.root,
        manifest: engine_graph.manifest,
    })
}

fn validate_project_engine(
    engine: &EngineManifest,
    project: &ProjectManifest,
) -> Result<(), ProjectManifestError> {
    if engine.engine.version != project.project.engine_version {
        return Err(ProjectManifestError::EngineVersionMismatch {
            engine: engine.engine.id.clone(),
            actual: engine.engine.version.clone(),
            expected: project.project.engine_version.clone(),
        });
    }
    Ok(())
}

fn resolve_project_gems_with_engine_root(
    project_root: impl AsRef<Path>,
    engine_root: impl AsRef<Path>,
    manifest: &ProjectManifest,
) -> Result<Vec<ResolvedProjectGem>, ProjectManifestError> {
    manifest.validate()?;
    let project_root = project_root.as_ref();
    let engine_root = engine_root.as_ref();
    let project_candidates = load_project_gem_candidates(project_root, manifest)?;
    resolve_project_gems_with_candidates(project_root, engine_root, manifest, project_candidates)
}

fn load_project_gem_candidates(
    project_root: &Path,
    manifest: &ProjectManifest,
) -> Result<BTreeMap<String, ResolvedProjectGem>, ProjectManifestError> {
    let mut candidates = BTreeMap::new();
    for declaration in manifest.gems.iter().filter(|gem| gem.path.is_some()) {
        let path = declaration
            .path
            .as_ref()
            .expect("project gem candidate has a path");
        let root = project_relative_path(project_root, path);
        let manifest_path = gem_manifest_path(&root);
        let gem_manifest = load_gem_manifest(&root)?;
        if gem_manifest.gem.id != declaration.id {
            return Err(ProjectManifestError::ProjectGemIdMismatch {
                declared: declaration.id.clone(),
                actual: gem_manifest.gem.id,
                path: gem_manifest_path(&root),
            });
        }
        candidates.insert(
            declaration.id.clone(),
            ResolvedProjectGem {
                declaration: declaration.clone(),
                kind: ResolvedGemKind::Project,
                provenance: GemProvenance {
                    home: GemHome::Project,
                    catalog_id: manifest.project.id.clone(),
                    catalog_path: project_manifest_path(project_root),
                    manifest_checksum: gem_manifest_checksum(&manifest_path)?,
                    manifest_path,
                },
                root,
                lock_root: path.clone(),
                manifest: gem_manifest,
            },
        );
    }
    Ok(candidates)
}

fn project_selection_requires_engine(
    manifest: &ProjectManifest,
    project_candidates: &BTreeMap<String, ResolvedProjectGem>,
) -> bool {
    let mut pending = manifest
        .gems
        .iter()
        .filter(|gem| gem.enabled)
        .map(|gem| gem.id.as_str())
        .collect::<Vec<_>>();
    let mut visited = HashSet::new();

    while let Some(id) = pending.pop() {
        if !visited.insert(id) {
            continue;
        }
        let Some(candidate) = project_candidates.get(id) else {
            return true;
        };
        pending.extend(
            candidate
                .manifest
                .dependencies
                .iter()
                .map(|dependency| dependency.id.as_str()),
        );
    }

    false
}

fn resolve_project_gems_with_candidates(
    _project_root: &Path,
    engine_root: &Path,
    manifest: &ProjectManifest,
    project_candidates: BTreeMap<String, ResolvedProjectGem>,
) -> Result<Vec<ResolvedProjectGem>, ProjectManifestError> {
    let engine_catalog_path = engine_manifest_path(engine_root);
    let engine_manifest = if project_selection_requires_engine(manifest, &project_candidates)
        || engine_catalog_path.is_file()
    {
        Some(load_engine_manifest(engine_root)?)
    } else {
        None
    };
    let mut candidates = project_candidates;
    if let Some(engine_manifest) = &engine_manifest {
        for (id, candidate) in &candidates {
            if engine_manifest.gem(id).is_some() {
                return Err(ProjectManifestError::AmbiguousGemProvenance {
                    id: id.clone(),
                    project_catalog: candidate.provenance.catalog_path.clone(),
                    engine_catalog: engine_catalog_path,
                });
            }
        }
    }
    let mut selected_capabilities = BTreeMap::<String, BTreeSet<String>>::new();
    let mut visited = HashSet::new();
    let mut stack = Vec::new();
    let mut order = Vec::new();

    for declaration in manifest.gems.iter().filter(|gem| gem.enabled) {
        visit_project_gem(
            &declaration.id,
            None,
            None,
            &declaration.capabilities,
            engine_root,
            engine_manifest.as_ref(),
            &mut candidates,
            &mut selected_capabilities,
            &mut visited,
            &mut stack,
            &mut order,
        )?;
    }

    let mut gems = Vec::with_capacity(order.len());
    for id in order {
        let mut resolved = candidates
            .remove(&id)
            .expect("visited gem remains in the candidate catalog");
        resolved.declaration.enabled = true;
        resolved.declaration.capabilities = selected_capabilities
            .remove(&id)
            .unwrap_or_default()
            .into_iter()
            .collect();
        // A linkage override is only ever declared by the project, never by a
        // gem that pulled this one in as a dependency.
        resolved.declaration.linkage = manifest
            .gems
            .iter()
            .find(|declaration| declaration.id == id)
            .and_then(|declaration| declaration.linkage);
        validate_resolved_gem_capabilities(&resolved)?;
        gems.push(resolved);
    }
    validate_project_gem_config(manifest, &gems)?;
    Ok(gems)
}

fn validate_project_gem_config(
    manifest: &ProjectManifest,
    gems: &[ResolvedProjectGem],
) -> Result<(), ProjectManifestError> {
    for (gem_id, config) in &manifest.gem_config {
        let Some(gem) = gems.iter().find(|gem| gem.manifest.gem.id == *gem_id) else {
            return Err(ProjectManifestError::UnknownConfiguredGem {
                gem_id: gem_id.clone(),
            });
        };
        if gem.provenance.home != GemHome::Engine {
            return Err(ProjectManifestError::InvalidConfiguredGemHome {
                gem_id: gem_id.clone(),
            });
        }
        let Some(schema) = &gem.manifest.configuration_schema else {
            return Err(ProjectManifestError::InvalidGemConfiguration {
                gem_id: gem_id.clone(),
                reason: "selected engine gem does not publish a configuration schema".to_string(),
            });
        };
        schema.validate_config(gem_id, config)?;
    }
    Ok(())
}

#[allow(clippy::too_many_arguments)]
fn visit_project_gem(
    id: &str,
    required_by: Option<&str>,
    version_requirement: Option<&str>,
    capabilities: &[String],
    engine_root: &Path,
    engine_manifest: Option<&EngineManifest>,
    candidates: &mut BTreeMap<String, ResolvedProjectGem>,
    selected_capabilities: &mut BTreeMap<String, BTreeSet<String>>,
    visited: &mut HashSet<String>,
    stack: &mut Vec<String>,
    order: &mut Vec<String>,
) -> Result<(), ProjectManifestError> {
    if !candidates.contains_key(id) {
        let Some(engine_manifest) = engine_manifest else {
            return Err(unknown_gem_error(required_by, id, engine_root));
        };
        let Some(declaration) = engine_manifest.gem(id) else {
            return Err(unknown_gem_error(required_by, id, engine_root));
        };
        let engine_gem = resolve_engine_gem_declaration(engine_root, declaration)?;
        let manifest_path = gem_manifest_path(&engine_gem.root);
        candidates.insert(
            id.to_string(),
            ResolvedProjectGem {
                declaration: ProjectGem {
                    id: id.to_string(),
                    enabled: true,
                    capabilities: Vec::new(),
                    linkage: None,
                    path: None,
                },
                kind: ResolvedGemKind::Engine,
                provenance: GemProvenance {
                    home: GemHome::Engine,
                    catalog_id: engine_manifest.engine.id.clone(),
                    catalog_path: engine_manifest_path(engine_root),
                    manifest_checksum: gem_manifest_checksum(&manifest_path)?,
                    manifest_path,
                },
                root: engine_gem.root,
                lock_root: engine_gem.declaration.path,
                manifest: engine_gem.manifest,
            },
        );
    }

    let candidate = candidates
        .get(id)
        .expect("selected gem is present in the candidate catalog");
    if let (Some(gem_id), Some(requirement)) = (required_by, version_requirement) {
        validate_gem_dependency_version(gem_id, requirement, candidate)?;
    }
    selected_capabilities
        .entry(id.to_string())
        .or_default()
        .extend(capabilities.iter().cloned());

    if visited.contains(id) {
        return Ok(());
    }
    if let Some(start) = stack.iter().position(|entry| entry == id) {
        let mut cycle = stack[start..].to_vec();
        cycle.push(id.to_string());
        return Err(ProjectManifestError::GemDependencyCycle {
            cycle: cycle.join(" -> "),
        });
    }

    let dependencies = candidate.manifest.dependencies.clone();
    stack.push(id.to_string());
    for dependency in &dependencies {
        visit_project_gem(
            &dependency.id,
            Some(id),
            dependency.version.as_deref(),
            &dependency.capabilities,
            engine_root,
            engine_manifest,
            candidates,
            selected_capabilities,
            visited,
            stack,
            order,
        )?;
    }
    let popped = stack.pop();
    debug_assert_eq!(popped.as_deref(), Some(id));
    visited.insert(id.to_string());
    order.push(id.to_string());
    Ok(())
}

fn unknown_gem_error(
    required_by: Option<&str>,
    id: &str,
    engine_root: &Path,
) -> ProjectManifestError {
    required_by.map_or_else(
        || ProjectManifestError::UnknownEngineGem {
            id: id.to_string(),
            path: engine_manifest_path(engine_root),
        },
        |gem_id| ProjectManifestError::UnknownGemDependency {
            gem_id: gem_id.to_string(),
            dependency_id: id.to_string(),
        },
    )
}

fn validate_gem_dependency_version(
    gem_id: &str,
    requirement: &str,
    dependency: &ResolvedProjectGem,
) -> Result<(), ProjectManifestError> {
    let parsed_requirement = VersionReq::parse(requirement)
        .expect("gem dependency version requirements are validated while loading manifests");
    let actual = Version::parse(&dependency.manifest.gem.version).ok();
    if actual
        .as_ref()
        .is_some_and(|actual| parsed_requirement.matches(actual))
    {
        return Ok(());
    }
    Err(ProjectManifestError::GemDependencyVersionMismatch {
        gem_id: gem_id.to_string(),
        dependency_id: dependency.manifest.gem.id.clone(),
        requirement: requirement.to_string(),
        actual: dependency.manifest.gem.version.clone(),
    })
}

/// Every asset source root the project and its resolved gems contribute, in
/// tier order.
///
/// # Errors
///
/// Returns any error [`ProjectManifest::validate`] and
/// [`resolve_project_gems`] return, plus
/// [`ProjectManifestError::DuplicateResolvedAssetRoot`] if two roots resolve to
/// the same id and [`ProjectManifestError::UnknownAssetOverrideRoot`] if an
/// override names a root the closure does not contain.
pub fn resolve_project_source_roots(
    project_root: impl AsRef<Path>,
    manifest: &ProjectManifest,
) -> Result<Vec<ResolvedProjectSourceRoot>, ProjectManifestError> {
    manifest.validate()?;
    let project_root = project_root.as_ref();
    let gems = resolve_project_gems(project_root, manifest)?;
    project_source_roots_from_resolved(project_root, manifest, &gems)
}

/// The project graph, refusing to proceed unless the committed lock matches it.
///
/// # Errors
///
/// Returns any error [`hydrate_project_local_state`],
/// [`load_project_manifest`], and [`resolve_project_graph`] return, plus
/// [`ProjectManifestError::MissingProjectLock`] if `azoth.lock` is absent and
/// [`ProjectManifestError::StaleProjectLock`] if it disagrees with the freshly
/// resolved graph.
pub fn load_resolved_project_graph(
    project_root: impl AsRef<Path>,
) -> Result<ResolvedProjectGraph, ProjectManifestError> {
    let project_root = project_root.as_ref();
    hydrate_project_local_state(project_root)?;
    let manifest = load_project_manifest(project_root)?;
    let mut graph = resolve_project_graph(project_root, manifest)?;
    let committed_lock = load_project_lock(project_root).map_err(|error| match error {
        ProjectManifestError::Read { path, source }
            if source.kind() == std::io::ErrorKind::NotFound =>
        {
            ProjectManifestError::MissingProjectLock { path }
        }
        other => other,
    })?;
    if committed_lock != graph.lock {
        return Err(ProjectManifestError::StaleProjectLock {
            path: project_lock_path(project_root),
        });
    }
    graph.lock = committed_lock;
    Ok(graph)
}

/// The project graph plus a verdict on the committed lock.
///
/// Unlike [`load_resolved_project_graph`], a missing, stale, or unreadable lock
/// is reported as a [`ProjectLockStatus`] rather than refused.
///
/// # Errors
///
/// Returns any error [`hydrate_project_local_state`],
/// [`load_project_manifest`], and [`resolve_project_graph`] return.
pub fn load_resolved_project_graph_with_lock_status(
    project_root: impl AsRef<Path>,
) -> Result<ResolvedProjectGraphLoad, ProjectManifestError> {
    let project_root = project_root.as_ref();
    hydrate_project_local_state(project_root)?;
    let manifest = load_project_manifest(project_root)?;
    let graph = resolve_project_graph(project_root, manifest)?;
    let lock_path = project_lock_path(project_root);
    let lock_status = match load_project_lock(project_root) {
        Ok(committed_lock) if committed_lock == graph.lock => ProjectLockStatus::Fresh,
        Ok(_) => ProjectLockStatus::Stale { path: lock_path },
        Err(ProjectManifestError::Read { path, source })
            if source.kind() == std::io::ErrorKind::NotFound =>
        {
            ProjectLockStatus::Missing { path }
        }
        Err(error) => ProjectLockStatus::Unavailable {
            path: lock_path,
            diagnostic: error.to_string(),
        },
    };

    Ok(ResolvedProjectGraphLoad { graph, lock_status })
}

/// Resolve engine, gems, source roots, and lock into one graph, without
/// reading or writing the committed `azoth.lock`.
///
/// # Errors
///
/// Returns any error [`ProjectManifest::validate`],
/// [`resolve_project_engine_root`], [`resolve_project_gems`],
/// [`resolve_project_source_roots`], and [`ProjectLock::validate`] return.
pub fn resolve_project_graph(
    project_root: impl AsRef<Path>,
    manifest: ProjectManifest,
) -> Result<ResolvedProjectGraph, ProjectManifestError> {
    manifest.validate()?;
    let project_root = project_root.as_ref();
    let engine = resolve_project_engine_at(resolve_project_engine_root(project_root)?, &manifest)?;
    let gems = resolve_project_gems_with_engine_root(project_root, &engine.root, &manifest)?;
    let source_roots = project_source_roots_from_resolved(project_root, &manifest, &gems)?;
    let lock = ProjectLock::from_project_engine_and_gems(&manifest, &engine.manifest, &gems);
    lock.validate()?;
    Ok(ResolvedProjectGraph {
        root: project_root.to_path_buf(),
        manifest,
        gems,
        source_roots,
        asset_overrides: lock.asset_overrides.clone(),
        lock,
    })
}

fn project_source_roots_from_resolved(
    project_root: &Path,
    manifest: &ProjectManifest,
    gems: &[ResolvedProjectGem],
) -> Result<Vec<ResolvedProjectSourceRoot>, ProjectManifestError> {
    let project_id = manifest.project.id.clone();
    let mut source_roots = Vec::new();

    for root in manifest.effective_asset_roots() {
        source_roots.push(ResolvedProjectSourceRoot {
            id: root.id.clone(),
            owner_id: project_id.clone(),
            root: project_relative_path(project_root, &root.path),
            display_name: project_asset_root_display_name(&root),
            portable_key: PortableKey::project_asset_root(&project_id, &root.id),
            tier: root.effective_tier(),
            mount: root.mount,
            recursive: root.recursive,
            watch: root.watch,
            writable: true,
            output_prefix: PROJECT_ASSETS_OUTPUT_PREFIX.to_string(),
        });
    }

    let present_roles = project_target_roles(manifest);
    for gem in gems {
        let gem_id = gem.manifest.gem.id.clone();
        for contribution in active_asset_contributions(gem, &present_roles) {
            let root = contribution
                .root
                .as_ref()
                .expect("validated assets contribution has a root");
            source_roots.push(ResolvedProjectSourceRoot {
                id: gem_asset_root_id(&gem_id, &contribution.id),
                owner_id: gem_id.clone(),
                root: project_relative_path(&gem.root, root),
                display_name: gem_asset_contribution_display_name(
                    &gem.manifest.gem.name,
                    &contribution.id,
                ),
                portable_key: PortableKey::gem_asset_contribution(&gem_id, &contribution.id),
                mount: contribution.effective_mount(),
                tier: gem_asset_root_tier(gem, contribution),
                recursive: contribution.recursive.unwrap_or(true),
                watch: contribution
                    .watch
                    .unwrap_or(gem.provenance.home == GemHome::Project),
                writable: gem.provenance.home == GemHome::Project,
                output_prefix: String::new(),
            });
        }
    }

    // A stable sort keeps the resolved closure order inside each tier.
    source_roots.sort_by_key(|root| root.tier);
    validate_resolved_asset_roots(&source_roots, &manifest.asset_overrides)?;
    Ok(source_roots)
}

/// The lock this project and its resolved gems imply, without writing it.
///
/// # Errors
///
/// Returns any error [`resolve_project_engine_root`],
/// [`resolve_project_gems`], [`resolve_project_source_roots`], and
/// [`ProjectLock::validate`] return.
pub fn resolve_project_lock(
    project_root: impl AsRef<Path>,
    manifest: &ProjectManifest,
) -> Result<ProjectLock, ProjectManifestError> {
    let project_root = project_root.as_ref();
    let engine = resolve_project_engine_at(resolve_project_engine_root(project_root)?, manifest)?;
    let gems = resolve_project_gems_with_engine_root(project_root, &engine.root, manifest)?;
    project_source_roots_from_resolved(project_root, manifest, &gems)?;
    let lock = ProjectLock::from_project_engine_and_gems(manifest, &engine.manifest, &gems);
    lock.validate()?;
    Ok(lock)
}

fn active_asset_contributions<'a>(
    gem: &'a ResolvedProjectGem,
    present_roles: &BTreeSet<GemTargetRole>,
) -> Vec<&'a GemContribution> {
    let mut active = BTreeMap::new();
    for role in present_roles {
        for contribution in crate::capability::selected_gem_contributions_for_role(
            &gem.manifest,
            &gem.declaration.capabilities,
            *role,
        ) {
            if contribution.kind == GemContributionKind::Assets {
                active.insert(contribution.id.as_str(), contribution);
            }
        }
    }
    active.into_values().collect()
}

