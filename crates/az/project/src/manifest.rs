impl LockedPackage {
    fn validate(&self) -> Result<(), ProjectManifestError> {
        if self.id.trim().is_empty() {
            return Err(ProjectManifestError::InvalidProjectLock {
                message: "package id cannot be empty".to_string(),
            });
        }
        validate_portable_lock_package_id("package", &self.id)?;

        if self.name.trim().is_empty() {
            return Err(ProjectManifestError::InvalidProjectLock {
                message: format!("package `{}` name cannot be empty", self.id),
            });
        }

        let mut capabilities = HashSet::new();
        for capability in &self.capabilities {
            validate_portable_lock_package_id("package capability", capability)?;
            if !capabilities.insert(capability) {
                return Err(ProjectManifestError::InvalidProjectLock {
                    message: format!(
                        "package `{}` capability `{capability}` appears more than once",
                        self.id
                    ),
                });
            }
        }

        if let Some(deprecation) = &self.deprecation {
            deprecation.validate(&self.id)?;
        }

        match (self.kind, &self.provenance) {
            (LockedPackageKind::Project, None) => {}
            (LockedPackageKind::Project, Some(_)) => {
                return Err(ProjectManifestError::InvalidProjectLock {
                    message: format!("project package `{}` cannot have gem provenance", self.id),
                });
            }
            (_, Some(provenance)) => provenance.validate(&self.id, self.kind)?,
            (_, None) => {
                return Err(ProjectManifestError::InvalidProjectLock {
                    message: format!("gem package `{}` is missing provenance", self.id),
                });
            }
        }

        let mut dependency_ids = HashSet::new();
        for dependency in &self.dependencies {
            dependency.validate(&self.id)?;
            if !dependency_ids.insert(dependency.id.clone()) {
                return Err(ProjectManifestError::InvalidProjectLock {
                    message: format!(
                        "package `{}` dependency `{}` appears more than once",
                        self.id, dependency.id
                    ),
                });
            }
        }

        for (contribution, fingerprint) in &self.contribution_fingerprints {
            validate_portable_lock_package_id("contribution", contribution)?;
            if !is_blake3_fingerprint(fingerprint) {
                return Err(ProjectManifestError::InvalidProjectLock {
                    message: format!(
                        "package `{}` contribution `{contribution}` has invalid fingerprint `{fingerprint}`",
                        self.id
                    ),
                });
            }
        }

        if self.root.as_os_str().is_empty() {
            return Err(ProjectManifestError::InvalidProjectLock {
                message: format!("package `{}` root cannot be empty", self.id),
            });
        }
        validate_lock_relative_path(format!("package `{}` root", self.id), &self.root, true)?;

        if self.manifest_path.as_os_str().is_empty() {
            return Err(ProjectManifestError::InvalidProjectLock {
                message: format!("package `{}` manifest path cannot be empty", self.id),
            });
        }
        validate_lock_relative_path(
            format!("package `{}` manifest path", self.id),
            &self.manifest_path,
            false,
        )?;

        Ok(())
    }
}

