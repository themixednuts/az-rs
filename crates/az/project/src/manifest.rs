impl ProjectServiceTarget {
    #[must_use]
    pub const fn canonical_name(role: ProjectServiceRole) -> &'static str {
        match role {
            ProjectServiceRole::ProjectHost => "project-host",
            ProjectServiceRole::AssetProcessor => "asset-processor",
            ProjectServiceRole::AssetWorker => "asset-worker",
            ProjectServiceRole::RuntimeHost => "runtime-host",
        }
    }

    #[must_use]
    pub fn cargo_bin(
        name: impl Into<String>,
        role: ProjectServiceRole,
        package: impl Into<String>,
        bin: impl Into<String>,
    ) -> Self {
        Self {
            name: name.into(),
            role,
            settings: None,
            package: package.into(),
            bin: bin.into(),
            default: true,
            args: Vec::new(),
            features: Vec::new(),
        }
    }

    fn validate(&self) -> Result<(), ProjectManifestError> {
        if self.name.trim().is_empty() {
            return Err(ProjectManifestError::MissingServiceTargetName);
        }

        let expected_name = Self::canonical_name(self.role);
        if self.name != expected_name {
            return Err(ProjectManifestError::InvalidServiceTargetNameForRole {
                name: self.name.clone(),
                role: self.role,
                expected: expected_name,
            });
        }

        if self.package.trim().is_empty() {
            return Err(ProjectManifestError::MissingServicePackage {
                target: self.name.clone(),
            });
        }

        if self.bin.trim().is_empty() {
            return Err(ProjectManifestError::MissingServiceBinary {
                target: self.name.clone(),
            });
        }

        if self
            .settings
            .as_deref()
            .is_some_and(|settings| settings.trim().is_empty())
        {
            return Err(ProjectManifestError::InvalidProjectLock {
                message: format!(
                    "service target `{}` settings profile cannot be empty",
                    self.name
                ),
            });
        }

        for arg in &self.args {
            if let Some(flag) = reserved_service_target_launch_arg(arg) {
                return Err(ProjectManifestError::ReservedServiceTargetArg {
                    target: self.name.clone(),
                    flag: flag.to_string(),
                });
            }
        }

        Ok(())
    }
}

