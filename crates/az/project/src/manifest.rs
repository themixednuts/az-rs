impl GemManifest {
    #[must_use]
    pub fn new(id: impl Into<String>, name: impl Into<String>, version: impl Into<String>) -> Self {
        Self {
            manifest: ManifestHeader {
                kind: GEM_MANIFEST_KIND.to_string(),
                schema: GEM_MANIFEST_SCHEMA.to_string(),
            },
            gem: GemMetadata {
                id: id.into(),
                name: name.into(),
                version: version.into(),
                origin: None,
                deprecation: None,
            },
            paths: GemPaths::default(),
            capabilities: BTreeMap::new(),
            contributions: Vec::new(),
            dependencies: Vec::new(),
            configuration_schema: None,
            tools: ProjectTools::default(),
        }
    }

    /// Check the whole gem manifest, table by table, in declaration order.
    ///
    /// # Errors
    ///
    /// Returns [`ProjectManifestError::InvalidKind`] or
    /// [`ProjectManifestError::InvalidSchema`] if the `[manifest]` header does
    /// not say `gem` / `azoth.gem/v1`;
    /// [`ProjectManifestError::MissingGemId`] or
    /// [`ProjectManifestError::MissingGemName`] for a blank id or name;
    /// [`ProjectManifestError::InvalidPackageId`] if the gem id or a
    /// capability key is not a portable package id;
    /// [`ProjectManifestError::ReservedGemId`] if the gem claims the engine's
    /// own id; [`ProjectManifestError::DuplicateGemContribution`] or
    /// [`ProjectManifestError::DuplicateGemDependency`] if two entries share an
    /// id; and [`ProjectManifestError::UnknownGemContribution`] if a capability
    /// names a contribution the manifest does not declare.
    ///
    /// It also returns any error the `[gem.origin]`, `[gem.deprecation]`,
    /// `[paths]`, contribution, capability, dependency,
    /// `[configuration_schema]`, and `[tools]` validators return.
    pub fn validate(&self) -> Result<(), ProjectManifestError> {
        if self.manifest.kind != GEM_MANIFEST_KIND {
            return Err(ProjectManifestError::InvalidKind {
                actual: self.manifest.kind.clone(),
                expected: GEM_MANIFEST_KIND,
            });
        }

        if self.manifest.schema != GEM_MANIFEST_SCHEMA {
            return Err(ProjectManifestError::InvalidSchema {
                actual: self.manifest.schema.clone(),
                expected: GEM_MANIFEST_SCHEMA,
            });
        }

        if self.gem.id.trim().is_empty() {
            return Err(ProjectManifestError::MissingGemId);
        }
        validate_portable_package_id("gem", &self.gem.id)?;
        if self.gem.id == ENGINE_ID {
            return Err(ProjectManifestError::ReservedGemId {
                id: self.gem.id.clone(),
            });
        }

        if self.gem.name.trim().is_empty() {
            return Err(ProjectManifestError::MissingGemName);
        }
        if let Some(origin) = &self.gem.origin {
            origin.validate(&self.gem.id)?;
        }
        if let Some(deprecation) = &self.gem.deprecation {
            deprecation.validate(&self.gem.id)?;
        }

        self.paths.validate()?;
        let mut contribution_ids = HashSet::new();
        for contribution in &self.contributions {
            contribution.validate(&self.gem.id)?;
            if !contribution_ids.insert(contribution.id.clone()) {
                return Err(ProjectManifestError::DuplicateGemContribution {
                    gem_id: self.gem.id.clone(),
                    contribution: contribution.id.clone(),
                });
            }
        }
        for (id, capability) in &self.capabilities {
            validate_portable_package_id("gem capability", id)?;
            capability.validate(&self.gem.id, id)?;
            for contribution in &capability.contributions {
                if !contribution_ids.contains(contribution) {
                    return Err(ProjectManifestError::UnknownGemContribution {
                        gem_id: self.gem.id.clone(),
                        capability: id.clone(),
                        contribution: contribution.clone(),
                    });
                }
            }
        }

        let mut dependency_ids = HashSet::new();
        for dependency in &self.dependencies {
            dependency.validate(&self.gem.id)?;
            if !dependency_ids.insert(dependency.id.clone()) {
                return Err(ProjectManifestError::DuplicateGemDependency {
                    gem_id: self.gem.id.clone(),
                    dependency_id: dependency.id.clone(),
                });
            }
        }

        if let Some(schema) = &self.configuration_schema {
            schema.validate(&self.gem.id)?;
        }

        self.tools.validate()?;

        Ok(())
    }
}

