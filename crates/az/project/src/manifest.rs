/// How a selected gem reaches a generated target (ADR 0036).
///
/// Absence of an override leaves the choice to the target role's default.
/// Push 1 generates the static flavor only; a declared `dynamic` override
/// records the project's intent for the dynamic flavor to consume.
#[derive(Debug, Clone, Copy, Serialize, Deserialize, PartialEq, Eq)]
#[serde(rename_all = "kebab-case")]
pub enum GemLinkage {
    /// Link the gem into every target that selects it, overriding a role
    /// default that would load it dynamically.
    Static,
    /// Load the gem as a separate artifact wherever the role default allows.
    Dynamic,
}

impl GemLinkage {
    /// The role default a project declaration overrides (ADR 0036).
    ///
    /// After ADR 0040 exactly one default survives: every host that can load
    /// gems at all is a prebuilt engine binary, so it loads them as artifacts.
    /// Ship targets are all-static by ADR 0035's ship rule, which is not a
    /// default and not overridable — a ship crate links its whole closure
    /// whatever this says.
    pub const DEFAULT: Self = Self::Dynamic;

    /// Role default plus the project's `[[gems]] linkage` override — the
    /// resolution ADR 0036 puts in `azoth.lock`.
    #[must_use]
    pub const fn resolve(declared: Option<Self>) -> Self {
        match declared {
            Some(declared) => declared,
            None => Self::DEFAULT,
        }
    }

    /// Whether a prebuilt host at this role can load the gem, or whether the
    /// gem opted out of reload and exists only where it is linked.
    #[must_use]
    pub const fn loadable(self) -> bool {
        matches!(self, Self::Dynamic)
    }
}

impl std::fmt::Display for GemLinkage {
    fn fmt(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        formatter.write_str(match self {
            Self::Static => "static",
            Self::Dynamic => "dynamic",
        })
    }
}

impl ProjectGem {
    fn validate(&self) -> Result<(), ProjectManifestError> {
        if self.id.trim().is_empty() {
            return Err(ProjectManifestError::MissingGemId);
        }
        validate_portable_package_id("project gem", &self.id)?;

        if let Some(path) = &self.path {
            validate_portable_manifest_path("project gem", path)?;
        }

        let mut capabilities = HashSet::new();
        for capability in &self.capabilities {
            validate_portable_package_id("gem capability", capability)?;
            if !capabilities.insert(capability) {
                return Err(ProjectManifestError::InvalidGemCapability {
                    gem_id: self.id.clone(),
                    capability: capability.clone(),
                    reason: "capability is selected more than once".to_string(),
                });
            }
        }

        Ok(())
    }
}

