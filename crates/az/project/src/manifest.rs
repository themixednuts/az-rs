impl EngineManifest {
    #[must_use]
    pub fn new(id: impl Into<String>, name: impl Into<String>, version: impl Into<String>) -> Self {
        Self {
            manifest: ManifestHeader {
                kind: ENGINE_MANIFEST_KIND.to_string(),
                schema: ENGINE_MANIFEST_SCHEMA.to_string(),
            },
            engine: EngineMetadata {
                id: id.into(),
                name: name.into(),
                version: version.into(),
            },
            source_control: SourceControlConfig::default(),
            contributions: Vec::new(),
            gems: Vec::new(),
        }
    }

    /// Check the whole engine manifest, table by table, in declaration order.
    ///
    /// # Errors
    ///
    /// Returns [`ProjectManifestError::InvalidKind`] or
    /// [`ProjectManifestError::InvalidSchema`] if the `[manifest]` header does
    /// not say `engine` / `azoth.engine/v1`;
    /// [`ProjectManifestError::MissingEngineId`],
    /// [`ProjectManifestError::MissingEngineName`], or
    /// [`ProjectManifestError::MissingEngineVersion`] for a blank field;
    /// [`ProjectManifestError::InvalidPackageId`] if the engine id is not a
    /// portable package id;
    /// [`ProjectManifestError::DuplicateGemContribution`] if two
    /// `[[contributions]]` share an id; and
    /// [`ProjectManifestError::DuplicateEngineGem`] if two `[[gems]]` do.
    ///
    /// It also returns any error the `[source_control]`, contribution, and
    /// `[[gems]]` validators return.
    pub fn validate(&self) -> Result<(), ProjectManifestError> {
        if self.manifest.kind != ENGINE_MANIFEST_KIND {
            return Err(ProjectManifestError::InvalidKind {
                actual: self.manifest.kind.clone(),
                expected: ENGINE_MANIFEST_KIND,
            });
        }

        if self.manifest.schema != ENGINE_MANIFEST_SCHEMA {
            return Err(ProjectManifestError::InvalidSchema {
                actual: self.manifest.schema.clone(),
                expected: ENGINE_MANIFEST_SCHEMA,
            });
        }

        if self.engine.id.trim().is_empty() {
            return Err(ProjectManifestError::MissingEngineId);
        }
        validate_portable_package_id("engine", &self.engine.id)?;

        if self.engine.name.trim().is_empty() {
            return Err(ProjectManifestError::MissingEngineName);
        }

        if self.engine.version.trim().is_empty() {
            return Err(ProjectManifestError::MissingEngineVersion);
        }

        self.source_control.validate()?;

        // The same stanza rules a gem's contributions answer to, because they
        // are the same stanzas.
        let mut contribution_ids = HashSet::new();
        for contribution in &self.contributions {
            contribution.validate(&self.engine.id)?;
            if !contribution_ids.insert(contribution.id.clone()) {
                return Err(ProjectManifestError::DuplicateGemContribution {
                    gem_id: self.engine.id.clone(),
                    contribution: contribution.id.clone(),
                });
            }
        }

        let mut gem_ids = HashSet::new();
        for gem in &self.gems {
            gem.validate()?;
            if !gem_ids.insert(gem.id.clone()) {
                return Err(ProjectManifestError::DuplicateEngineGem { id: gem.id.clone() });
            }
        }

        Ok(())
    }

    fn gem(&self, id: &str) -> Option<&EngineGem> {
        self.gems.iter().find(|gem| gem.id == id)
    }
}

