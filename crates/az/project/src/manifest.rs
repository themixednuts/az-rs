pub(crate) fn portable_package_id_error(id: &str) -> Option<String> {
    if id.trim() != id {
        return Some("must not have leading or trailing whitespace".to_string());
    }

    let mut chars = id.chars();
    let first = chars.next()?;
    if !first.is_ascii_alphanumeric() {
        return Some("must start with an ASCII letter or digit".to_string());
    }

    let last = id.chars().last()?;
    if !last.is_ascii_alphanumeric() {
        return Some("must end with an ASCII letter or digit".to_string());
    }

    for ch in id.chars() {
        if !(ch.is_ascii_alphanumeric() || matches!(ch, '.' | '_' | '-')) {
            return Some(format!(
                "contains unsupported character `{ch}`; use ASCII letters, digits, '.', '_', or '-'"
            ));
        }
    }

    if id.split('.').any(str::is_empty) {
        return Some("dot-separated namespace segments cannot be empty".to_string());
    }

    None
}

