fn portable_relative_path_error(path: &Path, allow_current_dir: bool) -> Option<String> {
    if path.as_os_str().is_empty() {
        return Some("cannot be empty".to_string());
    }

    if allow_current_dir && path == Path::new(".") {
        return None;
    }

    let Some(path_text) = path.to_str() else {
        return Some("must be valid UTF-8".to_string());
    };

    if path_text.trim() != path_text {
        return Some("must not have leading or trailing whitespace".to_string());
    }

    if path_text.starts_with('/') || path_text.starts_with('\\') {
        return Some("must be relative".to_string());
    }

    if path_text.contains(':') {
        return Some(
            "must not contain `:` because drive prefixes and alternate streams are not portable"
                .to_string(),
        );
    }

    for segment in path_text.split(['/', '\\']) {
        if segment.is_empty() {
            return Some("must not contain empty path segments".to_string());
        }
        if segment == "." {
            return Some("must not contain `.` path segments".to_string());
        }
        if segment == ".." {
            return Some("must not contain `..` path segments".to_string());
        }
    }

    for component in path.components() {
        match component {
            Component::Normal(_) => {}
            Component::CurDir => {
                return Some("must not contain `.` path segments".to_string());
            }
            Component::ParentDir => {
                return Some("must not contain `..` path segments".to_string());
            }
            Component::RootDir => {
                return Some("must be relative".to_string());
            }
            Component::Prefix(_) => {
                return Some("must not include a drive or UNC prefix".to_string());
            }
        }
    }

    None
}

fn default_assets_path() -> PathBuf {
    PathBuf::from("assets")
}

fn default_scripts_path() -> PathBuf {
    PathBuf::from("scripts")
}

fn default_debug_cargo_profile() -> String {
    "debug".to_string()
}

const fn default_true() -> bool {
    true
}

fn default_engine_root() -> PathBuf {
    let crate_dir = Path::new(env!("CARGO_MANIFEST_DIR"));
    engine_root_from_current_executable()
        .or_else(|| nearest_engine_root(crate_dir))
        .unwrap_or_else(|| crate_dir.to_path_buf())
}

fn engine_root_from_current_executable() -> Option<PathBuf> {
    std::env::current_exe()
        .ok()
        .as_deref()
        .and_then(nearest_engine_root)
}

fn nearest_engine_root(path: &Path) -> Option<PathBuf> {
    path.ancestors()
        .find(|candidate| engine_manifest_path(candidate).is_file())
        .map(Path::to_path_buf)
}

fn project_relative_path(project_root: &Path, path: &Path) -> PathBuf {
    if path.is_absolute() {
        path.to_path_buf()
    } else {
        project_root.join(platform_relative_path(path))
    }
}

fn lock_project_relative_path(path: &Path) -> PathBuf {
    path.to_path_buf()
}

fn lock_path_relative_to_package(package_root: &Path, path: &Path) -> PathBuf {
    package_root.join(path)
}

fn platform_relative_path(path: &Path) -> PathBuf {
    let mut normalized = PathBuf::new();
    for component in path.components() {
        if let Component::Normal(part) = component {
            normalized.push(part);
        }
    }
    normalized
}

