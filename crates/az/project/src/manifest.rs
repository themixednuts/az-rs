/// The tier one gem asset contribution resolves into: the contribution's
/// explicit override, or the tier the gem's home implies.
fn gem_asset_root_tier(gem: &ResolvedProjectGem, contribution: &GemContribution) -> AssetRootTier {
    contribution
        .tier
        .unwrap_or_else(|| gem.provenance.home.into())
}

fn validate_resolved_asset_roots(
    source_roots: &[ResolvedProjectSourceRoot],
    overrides: &[ProjectAssetOverride],
) -> Result<(), ProjectManifestError> {
    let mut by_id: BTreeMap<&str, Vec<PathBuf>> = BTreeMap::new();
    for root in source_roots {
        by_id.entry(&root.id).or_default().push(root.root.clone());
    }
    if let Some((id, roots)) = by_id.into_iter().find(|(_, roots)| roots.len() > 1) {
        return Err(ProjectManifestError::DuplicateResolvedAssetRoot {
            id: id.to_string(),
            roots,
        });
    }

    let ids = source_roots
        .iter()
        .map(|root| root.id.as_str())
        .collect::<HashSet<_>>();
    for declaration in overrides {
        for (role, root_id) in [
            ("winning", declaration.winning_root.as_str()),
            ("replaced", declaration.replaced_root.as_str()),
        ] {
            if !ids.contains(root_id) {
                return Err(ProjectManifestError::UnknownAssetOverrideRoot {
                    path: declaration.path.clone(),
                    role,
                    root_id: root_id.to_string(),
                });
            }
        }
    }
    Ok(())
}

fn default_locked_asset_root_id() -> String {
    "assets".to_string()
}

fn gem_manifest_checksum(path: &Path) -> Result<String, ProjectManifestError> {
    let bytes = std::fs::read(path).map_err(|source| ProjectManifestError::Read {
        path: path.to_path_buf(),
        source,
    })?;
    Ok(format!("blake3:{}", blake3::hash(&bytes).to_hex()))
}

fn is_blake3_fingerprint(value: &str) -> bool {
    value
        .strip_prefix("blake3:")
        .is_some_and(|hex| hex.len() == 64 && hex.bytes().all(|byte| byte.is_ascii_hexdigit()))
}

fn gem_contribution_fingerprints(manifest: &GemManifest) -> BTreeMap<String, String> {
    manifest
        .contributions
        .iter()
        .map(|contribution| {
            let canonical = toml::to_string(contribution)
                .expect("validated gem contributions always serialize as TOML");
            (
                contribution.id.clone(),
                format!("blake3:{}", blake3::hash(canonical.as_bytes()).to_hex()),
            )
        })
        .collect()
}

#[must_use]
pub fn project_id_from_name(name: &str) -> String {
    let mut id = String::with_capacity(name.len().max(7));

    let mut last_was_separator = false;
    for ch in name.trim().chars() {
        if ch.is_ascii_alphanumeric() {
            id.push(ch.to_ascii_lowercase());
            last_was_separator = false;
        } else if (ch == '_' || ch == '-' || ch.is_ascii_whitespace()) && !last_was_separator {
            id.push('_');
            last_was_separator = true;
        }
    }

    while id.ends_with('_') {
        id.pop();
    }

    if id.is_empty() {
        id.push_str("project");
    }

    id
}

