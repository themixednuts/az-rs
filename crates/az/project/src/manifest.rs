    /// A gem with no capabilities is active exactly for the roles its
    /// contributions declare — never for every role, which is what the pre-v2
    /// linkage field used to mean.
    fn assert_capability_free_gems_keep_declared_linkage(
        gems: &[ResolvedEngineGem],
        engine_manifest: &EngineManifest,
    ) {
        assert_eq!(gems.len(), engine_manifest.gems.len());
        assert!(
            gems.iter()
                .all(|gem| gem.manifest.manifest.schema == GEM_MANIFEST_SCHEMA)
        );

        let all_roles = [
            GemTargetRole::Game,
            GemTargetRole::P2p,
            GemTargetRole::Client,
            GemTargetRole::Server,
            GemTargetRole::Unified,
            GemTargetRole::HeadlessServer,
            GemTargetRole::ProjectHost,
            GemTargetRole::AssetProcessor,
            GemTargetRole::AssetWorker,
            GemTargetRole::RuntimeHost,
            GemTargetRole::Tool,
            GemTargetRole::NamedService,
        ];
        // ADR 0026 auth gems are capability-gated like eos/steam/gamedata.
        // Capability-free gems are active exactly for their declared role
        // contributions; presentation gems must not regain legacy all-role
        // linkage merely because their capability set is empty.
        for gem in gems.iter().filter(|gem| {
            !matches!(
                gem.manifest.gem.id.as_str(),
                "azoth.eos"
                    | "azoth.gamedata"
                    | "azoth.steam"
                    | "azoth.auth"
                    | "azoth.auth.eos"
                    | "azoth.auth.local"
                    | "azoth.auth.steam"
            )
        }) {
            assert!(gem.manifest.capabilities.is_empty());
            for role in all_roles {
                let expected = gem
                    .manifest
                    .contributions
                    .iter()
                    .any(|contribution| contribution.roles.contains(&role));
                assert_eq!(
                    crate::capability::selected_gem_contributions_apply_to(
                        &gem.manifest,
                        &[],
                        role,
                    ),
                    expected,
                    "{} did not project its declared linkage for {role}",
                    gem.manifest.gem.id,
                );
            }
        }
    }

