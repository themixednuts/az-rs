    #[test]
    fn resolution_carries_the_declared_linkage_override_onto_each_gem() {
        let temp = tempfile::tempdir().unwrap();
        for id in ["local.pinned", "local.default"] {
            let directory = id.replace('.', "-");
            write_gem_manifest(
                temp.path().join("gems").join(&directory),
                &GemManifest::new(id, id, "0.1.0"),
            )
            .unwrap();
        }

        let mut manifest = ProjectManifest::new("local.test", "Test", "0.1.0");
        manifest.gems.push(ProjectGem {
            id: "local.pinned".to_string(),
            enabled: true,
            capabilities: Vec::new(),
            linkage: Some(GemLinkage::Static),
            path: Some(PathBuf::from("gems/local-pinned")),
        });
        manifest.gems.push(ProjectGem {
            id: "local.default".to_string(),
            enabled: true,
            capabilities: Vec::new(),
            linkage: None,
            path: Some(PathBuf::from("gems/local-default")),
        });

        let gems = resolve_project_gems(temp.path(), &manifest).unwrap();
        let linkage = gems
            .iter()
            .map(|gem| (gem.manifest.gem.id.as_str(), gem.declaration.linkage))
            .collect::<BTreeMap<_, _>>();

        assert_eq!(linkage["local.pinned"], Some(GemLinkage::Static));
        assert_eq!(linkage["local.default"], None);

        // ADR 0036: the generator resolves role default plus override into the
        // lock, so a consumer reads one answer instead of re-deriving it.
        let engine = EngineManifest::new("azoth", "Azoth", "0.1.0");
        let lock = ProjectLock::from_project_engine_and_gems(&manifest, &engine, &gems);
        let recorded = lock
            .packages
            .iter()
            .map(|package| (package.id.as_str(), package.linkage))
            .collect::<BTreeMap<_, _>>();

        assert_eq!(recorded["local.pinned"], Some(GemLinkage::Static));
        assert_eq!(recorded["local.default"], Some(GemLinkage::Dynamic));
        // The project's own package is never linked as a gem.
        assert_eq!(recorded["local.test"], None);
    }

