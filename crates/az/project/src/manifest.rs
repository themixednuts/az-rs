/// Stable topology IDs persisted in `[topology].kind`.
#[derive(Debug, Clone, Copy, Serialize, Deserialize, PartialEq, Eq, Default)]
pub enum ProjectTopologyKind {
    #[default]
    #[serde(rename = "single-player")]
    SinglePlayer,
    #[serde(rename = "multiplayer-client-server")]
    MultiplayerClientServer,
    #[serde(rename = "multiplayer-peer-to-peer")]
    MultiplayerPeerToPeer,
}

impl ProjectTopologyKind {
    pub const ALL: [Self; 3] = [
        Self::SinglePlayer,
        Self::MultiplayerClientServer,
        Self::MultiplayerPeerToPeer,
    ];

    #[must_use]
    pub const fn as_manifest_id(self) -> &'static str {
        match self {
            Self::SinglePlayer => "single-player",
            Self::MultiplayerClientServer => "multiplayer-client-server",
            Self::MultiplayerPeerToPeer => "multiplayer-peer-to-peer",
        }
    }

    #[must_use]
    pub fn target_roles(self) -> BTreeSet<GemTargetRole> {
        let mut roles = BTreeSet::from([
            GemTargetRole::ProjectHost,
            GemTargetRole::AssetProcessor,
            GemTargetRole::AssetWorker,
            GemTargetRole::RuntimeHost,
        ]);
        match self {
            Self::SinglePlayer => {
                roles.insert(GemTargetRole::Game);
            }
            Self::MultiplayerClientServer => {
                roles.extend([
                    GemTargetRole::Client,
                    GemTargetRole::Server,
                    GemTargetRole::Unified,
                    GemTargetRole::HeadlessServer,
                ]);
            }
            Self::MultiplayerPeerToPeer => {
                roles.extend([GemTargetRole::Game, GemTargetRole::P2p]);
            }
        }
        roles
    }
}

