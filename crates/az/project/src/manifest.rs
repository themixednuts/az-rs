/// The optional `[source_control]` block.
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct SourceControlConfig {
    /// `[source_control.lore]` — the shared Lore service used by every checkout.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub lore: Option<LoreSourceControlConfig>,
}

impl SourceControlConfig {
    #[must_use]
    pub const fn is_empty(&self) -> bool {
        self.lore.is_none()
    }

    fn validate(&self) -> Result<(), ProjectManifestError> {
        if let Some(lore) = &self.lore {
            lore.validate()?;
        }
        Ok(())
    }
}

/// Portable connection coordinates for a Lore repository server.
///
/// Authentication tokens are intentionally absent: Lore owns them in its
/// machine-local credential store, while Azoth's service secrets use typed
/// `secret://` references.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct LoreSourceControlConfig {
    pub remote_url: String,
}

impl LoreSourceControlConfig {
    #[must_use]
    pub fn new(remote_url: impl Into<String>) -> Self {
        Self {
            remote_url: remote_url.into(),
        }
    }

    fn validate(&self) -> Result<(), ProjectManifestError> {
        let remote_url = self.remote_url.trim();
        let Some(authority_and_path) = remote_url.strip_prefix("lore://") else {
            return Err(ProjectManifestError::InvalidLoreSourceControlConfig {
                reason: "remote_url must use the lore:// scheme".to_string(),
            });
        };
        let authority = authority_and_path
            .split_once('/')
            .map_or(authority_and_path, |(authority, _)| authority);
        if remote_url != self.remote_url
            || authority.is_empty()
            || authority.chars().any(char::is_whitespace)
        {
            return Err(ProjectManifestError::InvalidLoreSourceControlConfig {
                reason: "remote_url must contain a non-empty authority without whitespace"
                    .to_string(),
            });
        }
        Ok(())
    }
}

/// The `[services]` host-tool manifest block (ADR 0026).
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct ProjectServices {
    /// `[services.auth]` — host composition settings, never client runtime state.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub auth: Option<AuthServiceConfig>,
}

impl ProjectServices {
    #[must_use]
    pub const fn is_empty(&self) -> bool {
        self.auth.is_none()
    }

    /// Whether the auth service is enabled (drives auth-host target generation).
    #[must_use]
    pub fn auth_enabled(&self) -> bool {
        self.auth.as_ref().is_some_and(|auth| auth.enabled)
    }

    /// Validate every configured service's cross-field invariants.
    fn validate(&self) -> Result<(), ProjectManifestError> {
        if let Some(auth) = &self.auth {
            auth.validate()
                .map_err(|error| ProjectManifestError::InvalidServiceConfig {
                    service: "auth".to_owned(),
                    reason: error.to_string(),
                })?;
        }
        Ok(())
    }
}

impl ProjectManifest {
    pub fn new(
        id: impl Into<String>,
        name: impl Into<String>,
        engine_version: impl Into<String>,
    ) -> Self {
        Self {
            manifest: ManifestHeader::default(),
            project: ProjectMetadata {
                id: id.into(),
                name: name.into(),
                version: "0.1.0".to_string(),
                engine_version: engine_version.into(),
                primary_gem: None,
            },
            source_control: SourceControlConfig::default(),
            topology: ProjectTopology::default(),
            paths: ProjectPaths::default(),
            asset_roots: vec![ProjectAssetRoot::default()],
            asset_overrides: Vec::new(),
            gems: Vec::new(),
            gem_config: BTreeMap::new(),
            secrets: ProjectSecrets::default(),
            services: ProjectServices::default(),
            packaging: ProjectPackaging::default(),
            runtime: ProjectRuntime::default(),
            tools: ProjectTools::default(),
        }
    }

    /// Check the whole project manifest, table by table, in declaration order.
    ///
    /// # Errors
    ///
    /// Returns [`ProjectManifestError::InvalidKind`] or
    /// [`ProjectManifestError::InvalidSchema`] if the `[manifest]` header does
    /// not say `project` / `azoth.project/v1`;
    /// [`ProjectManifestError::MissingProjectId`] or
    /// [`ProjectManifestError::MissingProjectName`] for a blank id or name;
    /// [`ProjectManifestError::InvalidPackageId`] if the project id, primary
    /// gem, or a configured gem key is not a portable package id;
    /// [`ProjectManifestError::DuplicateProjectGem`] if two `[[gems]]` entries
    /// share an id; [`ProjectManifestError::DuplicateProjectAssetRoot`] if two
    /// effective asset roots do; and
    /// [`ProjectManifestError::InvalidAssetOverride`] if the same
    /// path/winning-root/replaced-root triple is declared twice.
    ///
    /// It also returns any error the `[source_control]`, `[paths]`, asset-root,
    /// `[[gems]]`, `[services]`, `[packaging]`, `[runtime]`, and `[tools]`
    /// validators return.
    pub fn validate(&self) -> Result<(), ProjectManifestError> {
        if self.manifest.kind != PROJECT_MANIFEST_KIND {
            return Err(ProjectManifestError::InvalidKind {
                actual: self.manifest.kind.clone(),
                expected: PROJECT_MANIFEST_KIND,
            });
        }

        if self.manifest.schema != PROJECT_MANIFEST_SCHEMA {
            return Err(ProjectManifestError::InvalidSchema {
                actual: self.manifest.schema.clone(),
                expected: PROJECT_MANIFEST_SCHEMA,
            });
        }

        if self.project.id.trim().is_empty() {
            return Err(ProjectManifestError::MissingProjectId);
        }
        validate_portable_package_id("project", &self.project.id)?;

        if self.project.name.trim().is_empty() {
            return Err(ProjectManifestError::MissingProjectName);
        }
        if let Some(primary_gem) = &self.project.primary_gem {
            validate_portable_package_id("primary project gem", primary_gem)?;
        }

        self.source_control.validate()?;
        self.paths.validate()?;
        self.validate_asset_roots()?;

        let mut gem_ids = HashSet::new();
        for gem in &self.gems {
            gem.validate()?;
            if !gem_ids.insert(gem.id.clone()) {
                return Err(ProjectManifestError::DuplicateProjectGem { id: gem.id.clone() });
            }
        }

        for gem_id in self.gem_config.keys() {
            validate_portable_package_id("configured gem", gem_id)?;
        }

        self.secrets.validate()?;
        self.services.validate()?;
        self.packaging.validate()?;
        self.runtime.validate()?;
        self.tools.validate()?;

        Ok(())
    }

    fn validate_asset_roots(&self) -> Result<(), ProjectManifestError> {
        let mut root_ids = HashSet::new();
        for root in self.effective_asset_roots() {
            root.validate()?;
            if !root_ids.insert(root.id.clone()) {
                return Err(ProjectManifestError::DuplicateProjectAssetRoot { id: root.id });
            }
        }

        let mut overrides = HashSet::new();
        for declaration in &self.asset_overrides {
            declaration.validate()?;
            let path = declaration.normalized_path()?;
            if !overrides.insert((
                path,
                declaration.winning_root.clone(),
                declaration.replaced_root.clone(),
            )) {
                return Err(ProjectManifestError::InvalidAssetOverride {
                    path: declaration.path.clone(),
                    reason: "the same winning and replaced roots are declared more than once"
                        .to_string(),
                });
            }
        }
        Ok(())
    }

    /// Return explicit roots, or the v1 singular assets path as one project root.
    #[must_use]
    pub fn effective_asset_roots(&self) -> Vec<ProjectAssetRoot> {
        if self.asset_roots.is_empty() {
            vec![ProjectAssetRoot {
                path: self.paths.assets.clone(),
                ..ProjectAssetRoot::default()
            }]
        } else {
            self.asset_roots.clone()
        }
    }
}

