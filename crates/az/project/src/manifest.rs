#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
#[serde(deny_unknown_fields)]
pub struct ProjectBuildTarget {
    pub name: String,

    #[serde(default)]
    pub role: ProjectBuildTargetRole,

    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub settings: Option<String>,

    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub package: Option<String>,

    #[serde(default)]
    pub kind: ProjectBuildTargetKind,

    #[serde(default = "default_true")]
    pub default: bool,

    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub features: Vec<String>,

    /// Owner-root-relative files staged next to this target's Cargo build output.
    ///
    /// Paths must be relative and portable (no absolute paths, no `..` segments).
    /// Staging copies each file into the resolved Cargo profile output directory
    /// using only the source file name, so sibling runtime dependencies land next
    /// to the produced binary.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub runtime_files: Vec<String>,
}

impl ProjectBuildTarget {
    #[must_use]
    pub fn package(name: impl Into<String>, package: impl Into<String>) -> Self {
        Self {
            name: name.into(),
            role: ProjectBuildTargetRole::Generic,
            settings: None,
            package: Some(package.into()),
            kind: ProjectBuildTargetKind::Package,
            default: true,
            features: Vec::new(),
            runtime_files: Vec::new(),
        }
    }

    fn validate(&self) -> Result<(), ProjectManifestError> {
        if self.name.trim().is_empty() {
            return Err(ProjectManifestError::MissingBuildTargetName);
        }

        if self.kind == ProjectBuildTargetKind::Package
            && self
                .package
                .as_deref()
                .is_none_or(|package| package.trim().is_empty())
        {
            return Err(ProjectManifestError::MissingBuildPackage {
                target: self.name.clone(),
            });
        }

        if self
            .package
            .as_deref()
            .is_some_and(|package| package.trim().is_empty())
        {
            return Err(ProjectManifestError::MissingBuildPackage {
                target: self.name.clone(),
            });
        }

        if self
            .settings
            .as_deref()
            .is_some_and(|settings| settings.trim().is_empty())
        {
            return Err(ProjectManifestError::MissingBuildTargetSettings {
                target: self.name.clone(),
            });
        }

        for runtime_file in &self.runtime_files {
            if runtime_file.trim().is_empty() {
                return Err(ProjectManifestError::InvalidBuildTargetRuntimeFile {
                    target: self.name.clone(),
                    path: runtime_file.clone(),
                    reason: "cannot be empty".to_string(),
                });
            }
            if let Some(reason) = portable_relative_path_error(Path::new(runtime_file), false) {
                return Err(ProjectManifestError::InvalidBuildTargetRuntimeFile {
                    target: self.name.clone(),
                    path: runtime_file.clone(),
                    reason,
                });
            }
        }

        Ok(())
    }
}

