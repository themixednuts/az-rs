/// The process class a generated workspace supplies.
///
/// This is deliberately closed: generated target behavior is owned by the
/// schema, not inferred from a target name or a role string at render time.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "kebab-case")]
pub enum GeneratedTargetKind {
    Ship,
    Service(GeneratedServiceTarget),
}

/// The closed service process supplied by a generated workspace.
///
/// Keeping this separate from target names makes dependency and entrypoint
/// selection exhaustive. Adding a service means teaching every schema-owned
/// renderer about it; a string cannot silently inherit another service's
/// bootstrap.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "kebab-case")]
pub enum GeneratedServiceTarget {
    RuntimeHost,
    ProjectHost,
    AssetWorker,
}

impl GeneratedTargetKind {
    const fn name(self) -> &'static str {
        match self {
            Self::Ship => "ship",
            Self::Service(_) => "service",
        }
    }

    const fn schema_name(self) -> &'static str {
        match self {
            Self::Ship => "ship",
            Self::Service(GeneratedServiceTarget::RuntimeHost) => "service/runtime-host",
            Self::Service(GeneratedServiceTarget::ProjectHost) => "service/project-host",
            Self::Service(GeneratedServiceTarget::AssetWorker) => "service/asset-worker",
        }
    }
}

