/// How a contribution crate names the entry item generated glue calls, and how
/// the glue calls it.
///
/// Hashed into the generation fingerprint: changing the convention invalidates
/// every generated target, because every call site in them is derived from it.
/// The `8.1` bump moved activation out of the entry item and onto
/// `Composer::add`, where it reaches the contribution through its context —
/// same entry-item name, different call shape, so every rendered target is
/// stale until regenerated. The `8.2` bump put the engine floor in front of the
/// lock closure, which changes what every generated `compose()` composes and
/// not merely how it spells it. The `8.3` bump handed ship compositions whole
/// to `az_runtime_app::run`, so generated code could not carry a report from a
/// different composition. Schema 9 extends that ownership rule to static
/// service workspaces: each role-owned bootstrap receives the whole composer.
const ENTRY_CONVENTION: &str = "entry/v9: engine floor(), then <contribution-id>_contribution(), add(_, activation), role-owned-bootstrap(composer)";
