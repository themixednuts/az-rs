/// The const holding one contribution's product-capability activation.
///
/// Gem and contribution both spell it, because two gems may name their
/// contributions alike and both link into the same target.
fn activation_const(contribution: &LinkedContribution) -> String {
    format!(
        "{}__{}",
        upper_ident(&contribution.gem),
        upper_ident(&contribution.id)
    )
}

fn upper_ident(id: &str) -> String {
    id.replace(['-', '.'], "_").to_ascii_uppercase()
}

fn remove_legacy_generated_workspace(target_directory: &Path) -> Result<(), ProjectManifestError> {
    let legacy_root = target_directory.join("azoth").join("targets");
    if !legacy_root.exists() {
        return Ok(());
    }
    debug_assert!(legacy_root.starts_with(target_directory));
    if !legacy_root.starts_with(target_directory)
        || legacy_root.file_name().is_none_or(|name| name != "targets")
        || legacy_root.parent().and_then(Path::file_name) != Some(std::ffi::OsStr::new("azoth"))
    {
        return Err(invalid_targets(
            legacy_root,
            "refusing to remove a legacy generated target root outside target/azoth",
        ));
    }
    std::fs::remove_dir_all(&legacy_root).map_err(|source| ProjectManifestError::Write {
        path: legacy_root.clone(),
        source,
    })?;
    info!(legacy_root = %legacy_root.display(), "removed obsolete independent generated target workspace");
    Ok(())
}

fn write_generation_record(
    workspace_root: &Path,
    record: &GenerationRecord,
) -> Result<(), ProjectManifestError> {
    let mut bytes = serde_json::to_vec_pretty(record)
        .map_err(|error| invalid_targets(workspace_root.to_path_buf(), error.to_string()))?;
    bytes.push(b'\n');
    atomic_write(&workspace_root.join(GENERATION_FILE), &bytes)
}

fn write_bytes(path: &Path, contents: &[u8]) -> Result<(), ProjectManifestError> {
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent).map_err(|source| ProjectManifestError::Write {
            path: parent.to_path_buf(),
            source,
        })?;
    }
    std::fs::write(path, contents).map_err(|source| ProjectManifestError::Write {
        path: path.to_path_buf(),
        source,
    })
}

fn relative_path(base: &Path, target: &Path) -> Option<PathBuf> {
    let base_components = base.components().collect::<Vec<_>>();
    let target_components = target.components().collect::<Vec<_>>();
    if base_components.is_empty()
        || target_components.is_empty()
        || !same_root(&base_components, &target_components)
    {
        return None;
    }
    let mut common = 0;
    while common < base_components.len()
        && common < target_components.len()
        && component_eq(base_components[common], target_components[common])
    {
        common += 1;
    }
    let mut relative = PathBuf::new();
    for component in base_components[common..].iter().copied() {
        if matches!(component, Component::Normal(_)) {
            relative.push("..");
        }
    }
    for component in target_components[common..].iter().copied() {
        match component {
            Component::Normal(segment) => relative.push(segment),
            Component::CurDir => {}
            Component::ParentDir => relative.push(".."),
            Component::Prefix(_) | Component::RootDir => return None,
        }
    }
    if relative.as_os_str().is_empty() {
        relative.push(".");
    }
    Some(relative)
}

fn filesystem_path_eq(left: &Path, right: &Path) -> bool {
    let left = left.components().collect::<Vec<_>>();
    let right = right.components().collect::<Vec<_>>();
    left.len() == right.len()
        && left
            .into_iter()
            .zip(right)
            .all(|(left, right)| component_eq(left, right))
}

fn same_root(left: &[Component<'_>], right: &[Component<'_>]) -> bool {
    let mut left = left
        .iter()
        .copied()
        .take_while(|component| !matches!(component, Component::Normal(_)));
    let mut right = right
        .iter()
        .copied()
        .take_while(|component| !matches!(component, Component::Normal(_)));
    loop {
        match (left.next(), right.next()) {
            (Some(left), Some(right)) if component_eq(left, right) => {}
            (None, None) => return true,
            _ => return false,
        }
    }
}

fn component_eq(left: Component<'_>, right: Component<'_>) -> bool {
    #[cfg(windows)]
    {
        match (left, right) {
            (Component::Prefix(left), Component::Prefix(right)) => windows_prefix_eq(left, right),
            _ => windows_os_str_eq(left.as_os_str(), right.as_os_str()),
        }
    }
    #[cfg(not(windows))]
    {
        left == right
    }
}

#[cfg(windows)]
fn windows_prefix_eq(
    left: std::path::PrefixComponent<'_>,
    right: std::path::PrefixComponent<'_>,
) -> bool {
    use std::path::Prefix;

    match (left.kind(), right.kind()) {
        (
            Prefix::Disk(left) | Prefix::VerbatimDisk(left),
            Prefix::Disk(right) | Prefix::VerbatimDisk(right),
        ) => left.eq_ignore_ascii_case(&right),
        (
            Prefix::UNC(left_server, left_share) | Prefix::VerbatimUNC(left_server, left_share),
            Prefix::UNC(right_server, right_share) | Prefix::VerbatimUNC(right_server, right_share),
        ) => {
            windows_os_str_eq(left_server, right_server)
                && windows_os_str_eq(left_share, right_share)
        }
        _ => windows_os_str_eq(left.as_os_str(), right.as_os_str()),
    }
}

#[cfg(windows)]
fn windows_os_str_eq(left: &std::ffi::OsStr, right: &std::ffi::OsStr) -> bool {
    left.to_string_lossy()
        .eq_ignore_ascii_case(&right.to_string_lossy())
}

fn portable_path(path: &Path) -> String {
    let path = path.to_string_lossy().replace('\\', "/");
    if let Some(unc) = path.strip_prefix("//?/UNC/") {
        return format!("//{unc}");
    }
    if let Some(local) = path.strip_prefix("//?/") {
        return local.to_owned();
    }
    path
}

fn invalid_targets(path: PathBuf, reason: impl Into<String>) -> ProjectManifestError {
    ProjectManifestError::InvalidGeneratedTargets {
        path,
        reason: reason.into(),
    }
}

