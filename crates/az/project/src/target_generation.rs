    fn the_fingerprint_extends_over_capabilities_manifests_and_the_entry_convention() {
        let plans =
            vec![plan_for("client", vec![GemTargetRole::Client], &[runtime_gem()]).unwrap()];
        let manifests = manifests_for(&[runtime_gem()]);
        let baseline = {
            let mut hasher = Sha256::new();
            hash_schema_inputs(&mut hasher, &plans, &manifests);
            sha256_string(hasher)
        };

        let mut narrowed = plans.clone();
        narrowed[0].caps = CapSet::EMPTY.with(HostCapability::HostsWorld);
        let mut hasher = Sha256::new();
        hash_schema_inputs(&mut hasher, &narrowed, &manifests);
        assert_ne!(baseline, sha256_string(hasher));

        let mut reclassified = plans.clone();
        reclassified[0].kind = GeneratedTargetKind::Service(GeneratedServiceTarget::RuntimeHost);
        let mut hasher = Sha256::new();
        hash_schema_inputs(&mut hasher, &reclassified, &manifests);
        assert_ne!(baseline, sha256_string(hasher));

        let mut restated = manifests.clone();
        restated[0].manifest.digest.push_str("-other");
        let mut hasher = Sha256::new();
        hash_schema_inputs(&mut hasher, &plans, &restated);
        assert_ne!(baseline, sha256_string(hasher));

        // The convention itself is an input: every generated call site is
        // derived from it, so bumping it makes every rendered target stale.
        assert!(ENTRY_CONVENTION.contains("_contribution"));
        let mut hasher = Sha256::new();
        hash_inputs(
            &mut hasher,
            "entry/v8: <contribution-id>_contribution(ProductActivation)",
            &plans,
            &manifests,
        );
        assert_ne!(
            baseline,
            sha256_string(hasher),
            "the v8 call shape must not fingerprint as the current one"
        );
    }

