    #[test]
    fn the_engine_floor_composes_before_every_gem_and_only_where_its_role_says() {
        let client = target_main_source(
            &plan_for("client", vec![GemTargetRole::Client], &[runtime_gem()]).unwrap(),
            Path::new("project"),
            "Example",
        );

        // Order is the whole ruling: the floor is in place before a gem can
        // disagree with it, so a colliding gem entry loses at compose time
        // rather than winning by arriving first.
        let types = client
            .find("composer.floor(az_engine_types::types_contribution())?;")
            .expect("the engine types bundle composes");
        let assets = client
            .find("composer.floor(az_engine_assets::assets_contribution())?;")
            .expect("a client names the engine assets bundle");
        let gem = client
            .find("composer.add(sample_runtime::")
            .expect("the gem still composes");
        assert!(types < assets, "engine bundles keep manifest order");
        assert!(assets < gem, "the engine floor precedes every gem");

        // Role filtering is linkage, not decoration: a client neither composes
        // nor so much as names the builder bundle.
        assert!(!client.contains("az_engine_builders"));
        let manifest = package_manifest(
            &plan_for("client", vec![GemTargetRole::Client], &[runtime_gem()]).unwrap(),
        );
        assert!(manifest.contains("az-engine-types = { version = \"0.1.0\" }"));
        assert!(manifest.contains("az-engine-assets = { version = \"0.1.0\" }"));
        assert!(!manifest.contains("az-engine-builders"));
    }

