/// One engine contribution bundle a generated target links and composes.
///
/// It carries no activation and no `enabled` flag because there is nothing to
/// select: the engine floor is not a gem, and a project cannot switch off the
/// thing it is built on. What it does carry is the same entry-item call a gem
/// contribution does — that shared convention is what makes the generated glue
/// and a prebuilt engine host the same code (asset-contract ticket 014, D6).
#[derive(Debug, Clone, PartialEq, Eq)]
struct EngineBundle {
    /// Contribution id from `engine.toml`, for the generated comment.
    id: String,
    package: String,
    /// The bundle package's Rust name. Engine package names are engine-chosen,
    /// so unlike a project's they need no rename to be spellable.
    alias: String,
    entry: String,
}

#[derive(Debug, Clone)]
struct LinkDependency {
    package: String,
    /// Cargo dependency rename, so the generated glue never has to guess the
    /// Rust path of a project-authored package name.
    alias: String,
    path: Option<PathBuf>,
    features: BTreeSet<String>,
    /// When true, emit `default-features = false` so the linked package's
    /// package-default feature set cannot silently pull role-inappropriate
    /// code into a generated target (compile-graph audit P1-4).
    default_features: bool,
    contributions: Vec<LinkedContribution>,
}

/// One contribution the target's glue constructs by name.
#[derive(Debug, Clone)]
struct LinkedContribution {
    gem: String,
    id: String,
    /// The entry item the gem's package exports for this contribution.
    entry: String,
    /// Product-capability activation: the selected capability ids in their
    /// runtime form. Empty for a source-built gem, whose selection already
    /// lowered to Cargo features.
    activation: Vec<String>,
}

#[derive(Debug, Clone)]
struct FilteredContribution {
    gem: String,
    id: String,
    roles: Vec<GemTargetRole>,
    miss: Miss,
}

/// Why a contribution of a selected gem is not in a target's composition.
///
/// Naming which of the two filters caught it is the point: a capability miss
/// reported as a role miss reads as "this gem is for other targets" when it
/// really means "the project did not select this".
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Miss {
    Role,
    Capability,
}

impl fmt::Display for Miss {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter.write_str(match self {
            Self::Role => "declares other roles",
            Self::Capability => "waits on an unselected capability",
        })
    }
}

